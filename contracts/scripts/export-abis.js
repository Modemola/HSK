// Writes the ABIs the agent needs to agent/src/chain/abis.ts.
const fs = require("fs");
const path = require("path");
const camel = (n) => (n === "MockUSDC" ? "mockUsdc" : n[0].toLowerCase() + n.slice(1));
const names = ["CorridorRegistry", "CorridorEscrow", "EvidenceAnchor", "MockUSDC"];
const art = (n) => {
  const sub = n === "MockUSDC" ? "test/MockUSDC.sol" : `${n}.sol`;
  return require(path.join(__dirname, "..", "artifacts", "contracts", sub, `${n}.json`));
};
let out = "// Generated by contracts/scripts/export-abis.js — do not edit.\n";
for (const n of names) out += `export const ${camel(n)}Abi = ${JSON.stringify(art(n).abi)} as const;\n`;
out += `export const mockUsdcBytecode = ${JSON.stringify(art("MockUSDC").bytecode)} as const;\n`;
for (const n of ["CorridorRegistry", "CorridorEscrow", "EvidenceAnchor"]) out += `export const ${n[0].toLowerCase() + n.slice(1)}Bytecode = ${JSON.stringify(art(n).bytecode)} as const;\n`;
const dest = path.join(__dirname, "..", "..", "agent", "src", "chain", "abis.ts");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log("wrote", dest);
